"""The domain, pure: what the real system believes, with no knowledge that a benchmark exists.

Holds the types every other package speaks (employee, team, work item, calendar event,
document, leave, and their ids), the predicate registry with each predicate's value
spec, the claim vocabulary with its per-type grading keys, ``RunContext`` and world
time, the fact base a run sees through a ``FactView`` under a ``RunCondition``, the
coverage that says which slices of the sources a view observed whole and the
function that computes it from a run's reads, the condition those reads show, the
structured projection of those reads that both the grader and the graded build on, the
frozen prefetch every system opens with as data with its planner and its digest, the
preregistration the harness and the evaluator both read, as plain data with its strict
codec and the procedure a bound registration shares with the frozen one it names, the
attribution table that reads what a model dispatch observed, the derivation that turns
an observed record into facts and gaps, and the
deterministic rules — closed-world evaluation per declared evidence domain, the
system-of-record authority table that resolves conflicting observations, viability of
a person for a need, constraint checks, and the reading pass that asks grounding and
viability of each impact together. The investigator's deterministic core and the
evaluator call the same rule functions from here, which makes that sharing visible
instead of duplicated (the answer-key contract in DESIGN says why sharing rules is
safe and sharing code between generator and evaluator is not). Vendor-neutral ports
that both the generator and the investigator consume sit here too; an abstraction
that describes how one vendor works stays inside that vendor's adapter.

Boundary: never imports ``world`` — the production investigator depends on the domain
without depending on the benchmark that grades it; performs no I/O; reads no clock —
world time arrives in ``RunContext``, and the wall clock is read only at a composition
root. Populated step by step through the world milestone; the layout is the decision.

Callers import the public names from the package (``from leaveimpact.core import
Employee``); the module split is a navigation aid, not part of the contract — with
one exception: the write ports are imported only by their module path,
``leaveimpact.core.ports.write``, and only by ``adapters`` and ``generator``, because
the import law enforces read-only on that path and a re-export here would launder it.
"""

